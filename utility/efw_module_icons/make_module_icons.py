"""Build EFW equipment-designer module icons from vanilla ones.

Each icon starts from a vanilla module icon, is recoloured with an "improvised"
material palette (wood, cardboard, rust, cast iron...) and gets deterministic
wear marks, so it reads as an EFW variant of the vanilla part.

usage: make_module_icons.py <mod_dir> <vanilla_dir> [preview_dir]
"""
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / 'efw_laws'))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from dds_tool import read_dds, write_dds, write_png
from draw_sails import small_sail, large_sail, W as SAIL_W, H as SAIL_H

P = 'gfx/interface/equipmentdesigner/planes/modules/'
N = 'gfx/interface/equipmentdesigner/naval/modules/icons/'

# palette = (shadow rgb, highlight rgb); wear = how many scratches/stains
ICONS = [
    # sprite prefix, module, vanilla base texture, palette, wear
    ('EMI', 'efw_wooden_boost_airframe', P + 'airplane_non_strategic_materials_icon.dds', ((70, 40, 18), (222, 170, 105)), 18),
    ('EMI', 'efw_improvised_drop_tank', P + 'airplane_drop_tanks_icon.dds', ((92, 70, 40), (226, 200, 150)), 14),
    ('EMI', 'efw_multirole_combat_rack', P + 'airplane_bomb_lock_icon.dds', ((60, 30, 18), (205, 120, 70)), 20),
    ('EMI', 'efw_cast_iron_stove_armor', P + 'airplane_armor_plate_small_icon.dds', ((22, 22, 26), (150, 145, 140)), 16),
    ('EMI', 'efw_bazooka_charlie_tubes', P + 'airplane_rocket_rail_icon.dds', ((38, 46, 22), (165, 175, 105)), 14),
    ('SMI', 'efw_improvised_fuel_tank', N + 'fuel_tank_icn.dds', ((62, 32, 20), (210, 130, 80)), 22),
    ('SMI', 'efw_careened_hull', N + 'armor_thin_icn.dds', ((70, 34, 14), (236, 160, 96)), 12),
]

# No vanilla sail exists to recolour: these are drawn (see draw_sails.py).
DRAWN = [
    ('SMI', 'efw_small_sail', small_sail),
    ('SMI', 'efw_large_sail', large_sail),
]


def lum(r, g, b):
    return (0.299 * r + 0.587 * g + 0.114 * b) / 255.0


def recolour(px, shadow, light):
    out = []
    for row in px:
        new = []
        for r, g, b, a in row:
            if a == 0:
                new.append((r, g, b, a))
                continue
            t = min(1.0, lum(r, g, b) * 1.15)
            c = tuple(int(s + (h - s) * t) for s, h in zip(shadow, light))
            new.append((*c, a))
        out.append(new)
    return out


def wear(px, seed, marks):
    """Darken short scratches and small stains, only on opaque pixels."""
    rnd = random.Random(seed)
    h, w = len(px), len(px[0])
    opaque = [(x, y) for y in range(h) for x in range(w) if px[y][x][3] > 200]
    if not opaque:
        return px
    for _ in range(marks):
        x, y = rnd.choice(opaque)
        if rnd.random() < 0.6:  # scratch
            dx, dy = rnd.choice(((1, 0), (1, 1), (0, 1), (1, -1)))
            for i in range(rnd.randint(2, 5)):
                xx, yy = x + dx * i, y + dy * i
                if 0 <= xx < w and 0 <= yy < h and px[yy][xx][3] > 200:
                    r, g, b, a = px[yy][xx]
                    px[yy][xx] = (int(r * .55), int(g * .55), int(b * .55), a)
        else:  # stain
            for yy in range(y - 1, y + 2):
                for xx in range(x - 1, x + 2):
                    if 0 <= xx < w and 0 <= yy < h and px[yy][xx][3] > 200:
                        r, g, b, a = px[yy][xx]
                        px[yy][xx] = (int(r * .75), int(g * .7), int(b * .65), a)
    return px


def main():
    mod, van = Path(sys.argv[1]), Path(sys.argv[2])
    preview = Path(sys.argv[3]) if len(sys.argv) > 3 else None
    out_dir = mod / 'gfx/interface/equipmentdesigner/efw_modules'
    out_dir.mkdir(parents=True, exist_ok=True)
    sprites = ['# Generated by utility/efw_module_icons/make_module_icons.py\n'
               '# Planes use GFX_EMI_<module>, ships GFX_SMI_<module> (modules without gfx =).\n'
               'spriteTypes = {\n']
    for i, (prefix, module, base, (shadow, light), marks) in enumerate(ICONS):
        w, h, px = read_dds(str(van / base))
        px = wear(recolour(px, shadow, light), seed=i * 7919 + 13, marks=marks)
        dst = out_dir / f'{module}.dds'
        write_dds(str(dst), w, h, px)
        if preview:
            write_png(str(preview / f'mod_{module}.png'), w, h, px, 3)
        sprites.append(f'\n    spriteType = {{\n        name = "GFX_{prefix}_{module}"\n'
                       f'        textureFile = "gfx/interface/equipmentdesigner/efw_modules/{module}.dds"\n    }}\n')
        print(f'GFX_{prefix}_{module}: {w}x{h} from {Path(base).name}')
    for prefix, module, draw in DRAWN:
        px = draw()
        write_dds(str(out_dir / f'{module}.dds'), SAIL_W, SAIL_H, px)
        if preview:
            write_png(str(preview / f'mod_{module}.png'), SAIL_W, SAIL_H, px, 3)
        sprites.append(f'\n    spriteType = {{\n        name = "GFX_{prefix}_{module}"\n'
                       f'        textureFile = "gfx/interface/equipmentdesigner/efw_modules/{module}.dds"\n    }}\n')
        print(f'GFX_{prefix}_{module}: {SAIL_W}x{SAIL_H} drawn')
    sprites.append('}\n')
    (mod / 'interface/efw_module_icons.gfx').write_text(''.join(sprites), encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
